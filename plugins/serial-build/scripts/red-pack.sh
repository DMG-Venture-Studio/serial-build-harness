#!/bin/sh
# The red-breaker agent's context pack, generated, never written by hand: what a
# breaker otherwise spends its first minutes reading, and then carries in every
# later turn. Printed as Markdown for the /serial-build:red skill to put in the
# brief. The breaker may still read anything; the pack only saves it the search.
#
#   - the gate, and the command that runs one test file (red.test_command);
#   - every file changed since the plan was committed, with its change count;
#   - the full text of the changed source files in the lane's slice (the lane's
#     "paths" in red.lanes; every changed file outside the test paths and docs/
#     when the lane names none or no lane is given);
#   - the signatures in the test support files (conftest, fixtures, helpers,
#     factories) under red.test_paths, so tests can reuse what exists.
#
# Files over 1500 lines, and anything past 200 KB in all, are named, not printed.
# --out PATH writes the pack to PATH, which must be outside the project (the
# red lock refuses writes inside it), so the breaker is told to read the file
# instead of having the pack retyped into its prompt.
# Usage: red-pack.sh [lane name] [--out PATH]    (from the project root)
set -u
SB_PLUGIN=$(cd "$(dirname "$0")/.." && pwd)
. "$SB_PLUGIN/scripts/lib.sh"
refuse() { printf 'red-pack: %s\n' "$1" >&2; exit 1; }
lane= out=
while [ $# -gt 0 ]; do
  case "$1" in
    --out) out=${2:-}; [ -n "$out" ] || refuse "--out needs a path"; shift ;;
    *) lane=$1 ;;
  esac
  shift
done
sb_load_config || refuse "no usable .claude/serial-build.json"
cd "$SB_ROOT" || exit 1
if [ -n "$out" ]; then
  sb_outside_project "$out" || refuse "--out must be an absolute path outside the project, its repository, and .git (the red lock refuses writes there): $out"
fi
plan=docs/plan.md
[ -f "$plan" ] || refuse "no docs/plan.md, so no gate to pack for"
gate=$(awk '/^# /{print substr($0, 3); exit}' "$plan")
since=$(git log --diff-filter=A --format=%H -1 -- "$plan" 2>/dev/null)
[ -n "$since" ] || refuse "docs/plan.md has never been committed"

lanekey=
if [ -n "$lane" ]; then
  i=0 n=$(sb_count "$SB_CFG" red.lanes)
  while [ "$i" -lt "$n" ]; do
    [ "$(sb_get "$SB_CFG" "red.lanes.$i.name")" = "$lane" ] && lanekey="red.lanes.$i"
    i=$((i + 1))
  done
  [ -n "$lanekey" ] || refuse "no lane named \"$lane\" under red.lanes in .claude/serial-build.json"
fi

if [ -n "$out" ]; then
  mkdir -p "$(dirname "$out")" || refuse "cannot make the folder for $out"
  exec 3>&1 > "$out"
fi
printf '# Context pack: %s%s\n\n' "$gate" "${lane:+, lane $lane}"
printf 'Generated by red-pack.sh from the project as committed at %s. It saves you the search; you may still read anything.\n\n' "$(git rev-parse --short HEAD)"
if [ -n "$lanekey" ]; then
  printf 'Your slice: %s\n\n' "$(sb_get "$SB_CFG" "$lanekey.focus" || echo "(no focus given)")"
fi
tc=$(sb_get "$SB_CFG" red.test_command) || tc=
printf '## Run one test file\n\n'
if [ -n "$tc" ]; then printf '    %s\n\n' "$tc"; else printf 'No red.test_command is configured; use the test commands in CLAUDE.md.\n\n'; fi

changed=$(git diff --name-only --relative "$since" HEAD -- . 2>/dev/null | LC_ALL=C sort)
printf '## Files changed since the plan was committed\n\n'
if [ -n "$changed" ]; then
  git diff --numstat --relative "$since" HEAD -- . | awk -F '\t' '{ printf "- %s (+%s -%s)\n", $3, $1, $2 }'
else
  echo "- none"
fi
echo

tests=$(printf '%s\n' "$changed" | sb_filter "$SB_CFG" red.test_paths)
slice=$(printf '%s\n' "$changed" | sed '/^$/d; /^docs\//d' | grep -vxF -e "${tests:-}" -e '' 2>/dev/null)
[ -z "$tests" ] && slice=$(printf '%s\n' "$changed" | sed '/^$/d; /^docs\//d')
if [ -n "$lanekey" ] && sb_get "$SB_CFG" "$lanekey.paths.#" >/dev/null; then
  slice=$(printf '%s\n' "$slice" | sb_filter "$SB_CFG" "$lanekey.paths")
fi

budget=204800 skipped=
printf '## Changed source in this slice, in full\n\n'
while IFS= read -r f; do
  [ -n "$f" ] && [ -f "$f" ] || continue
  lines=$(wc -l < "$f" | tr -d ' ')
  size=$(wc -c < "$f" | tr -d ' ')
  if [ "$lines" -gt 1500 ] || [ "$size" -gt "$budget" ]; then skipped="$skipped- $f ($lines lines)
"; continue; fi
  budget=$((budget - size))
  printf '### %s\n\n````\n' "$f"
  cat "$f"
  [ -n "$(tail -c 1 "$f")" ] && echo
  printf '````\n\n'
done <<EOF
$slice
EOF
[ -n "$slice" ] || printf 'No changed source in this slice.\n\n'
if [ -n "$skipped" ]; then printf 'Too large to print, read them yourself:\n%s\n' "$skipped"; fi

printf '## Test support: fixtures and helpers you can reuse\n\n'
support=$(git ls-files -- . | sb_filter "$SB_CFG" red.test_paths | awk '{ b = $0; sub(/.*\//, "", b); b = tolower(b) } b ~ /^(conftest|setup|testutil)|fixture|helper|factor|support/')
if [ -z "$support" ]; then
  echo "No support files found under the test paths."
else
  printf '%s\n' "$support" | while IFS= read -r f; do
    [ -f "$f" ] || continue
    grep -nE '^[[:space:]]*(@pytest\.fixture|@fixture|(async[[:space:]]+)?def[[:space:]]|class[[:space:]]|(export[[:space:]]+)?(async[[:space:]]+)?function[[:space:]]|export[[:space:]]+(const|let|class)[[:space:]]|func[[:space:]]|fn[[:space:]]|pub[[:space:]]+fn[[:space:]])' "$f" 2>/dev/null \
      | head -n 80 | sed "s|^|$f:|"
  done
fi
if [ -n "$out" ]; then
  exec 1>&3
  printf 'red-pack: wrote the context pack to %s (%s bytes)\n' "$out" "$(wc -c < "$out" | tr -d ' ')"
fi
exit 0
